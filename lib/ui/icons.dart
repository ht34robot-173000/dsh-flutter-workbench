/// 把 SVG path 数据解析成 Flutter 的 [Path]。
///
/// 只实现 Material Symbols 实际用到的子集：M/m（moveTo）、L/l（lineTo）、
/// H/h/V/v（水平/垂直线）、Q/q（二次贝塞尔）、T/t（平滑二次）、
/// C/c（三次贝塞尔）、S/s（平滑三次）、Z/z（close）。
///
/// 为什么自己写而不用 `path_drawing` 之类：
///   - 多一个依赖就多一份版本风险，而这些路径是**固定数据**，解析器不会变
///   - 只要支持这个子集就够（48 个图标全部覆盖），不需要完整 SVG 规范
///
/// 解析失败返回空 Path —— 界面上就是「少一个图标」，不会崩。
Path _parseSvgPath(String d) {
  final path = Path();
  // 用正则切 token：命令字母 + 数字（含负号、小数点、科学计数法）
  final re = RegExp(r'([MmLlHhVvQqTtCcSsZz])|(-?\d*\.?\d+(?:[eE][-+]?\d+)?)');
  final tokens = re.allMatches(d).map((m) => m.group(0)!).toList();

  var i = 0;
  String cmd = 'M';
  double cx = 0, cy = 0; // 当前点
  double startX = 0, startY = 0; // 子路径起点（Z 要回到这里）
  double lastCtrlX = 0, lastCtrlY = 0; // 上一段贝塞尔的第二控制点（S/T 要用）
  String prevCmd = '';

  double num() => double.parse(tokens[i++]);
  bool hasNum() => i < tokens.length && !RegExp(r'[A-Za-z]').hasMatch(tokens[i]);

  while (i < tokens.length) {
    if (RegExp(r'[A-Za-z]').hasMatch(tokens[i])) {
      cmd = tokens[i++];
    } else if (!hasNum()) {
      break;
    }

    final rel = cmd == cmd.toLowerCase();
    final c = cmd.toUpperCase();
    // 相对命令的基准点
    final bx = rel ? cx : 0.0;
    final by = rel ? cy : 0.0;

    switch (c) {
      case 'M':
        cx = bx + num();
        cy = by + num();
        startX = cx;
        startY = cy;
        path.moveTo(cx, cy);
        // M 后续的连续坐标对按 L 处理（SVG 规范）
        cmd = rel ? 'l' : 'L';
        break;
      case 'L':
        cx = bx + num();
        cy = by + num();
        path.lineTo(cx, cy);
        break;
      case 'H':
        cx = bx + num();
        path.lineTo(cx, cy);
        break;
      case 'V':
        cy = by + num();
        path.lineTo(cx, cy);
        break;
      case 'Q':
        final qx = bx + num(), qy = by + num();
        cx = bx + num();
        cy = by + num();
        path.quadraticBezierTo(qx, qy, cx, cy);
        lastCtrlX = qx;
        lastCtrlY = qy;
        break;
      case 'T':
        // 平滑二次：控制点 = 上一控制点关于当前点的反射
        final tx = 2 * cx - lastCtrlX;
        final ty = 2 * cy - lastCtrlY;
        cx = bx + num();
        cy = by + num();
        path.quadraticBezierTo(tx, ty, cx, cy);
        lastCtrlX = tx;
        lastCtrlY = ty;
        break;
      case 'C':
        final c1x = bx + num(), c1y = by + num();
        final c2x = bx + num(), c2y = by + num();
        cx = bx + num();
        cy = by + num();
        path.cubicTo(c1x, c1y, c2x, c2y, cx, cy);
        lastCtrlX = c2x;
        lastCtrlY = c2y;
        break;
      case 'S':
        // 平滑三次：第一控制点 = 上一第二控制点关于当前点的反射
        final sx = 2 * cx - lastCtrlX;
        final sy = 2 * cy - lastCtrlY;
        final c2x = bx + num(), c2y = by + num();
        cx = bx + num();
        cy = by + num();
        path.cubicTo(sx, sy, c2x, c2y, cx, cy);
        lastCtrlX = c2x;
        lastCtrlY = c2y;
        break;
      case 'Z':
        path.close();
        cx = startX;
        cy = startY;
        break;
    }

    if (c != 'Q' && c != 'T' && c != 'C' && c != 'S') {
      // 非曲线命令要清掉上一控制点，否则后面的 S/T 会算错
      lastCtrlX = cx;
      lastCtrlY = cy;
    }
    prevCmd = cmd;
  }
  // prevCmd 留着方便以后加调试，不参与逻辑
  assert(prevCmd.isNotEmpty || tokens.isEmpty);
  return path;
}

/// 一个用自有路径绘制的图标。
///
/// 尺寸控制（阶段②连踩五轮，最终方案）：
///
///   1. `CustomPaint(size:)` 在 Row 里被拉到整行宽
///   2. `SizedBox` 包它 → 无 child 的 CustomPaint 取 constraints.biggest
///   3. `SizedBox` + `FittedBox` → 撑开意愿更强
///   4. `CustomPaint(child: SizedBox.shrink())` → 反过来压成 0×0，不显示
///   5. `LeafRenderObjectWidget` 自己 performLayout → 能画出图，但在
///      Row 里仍会与相邻 Text 抢宽度，图标浮到文字上方
///
///   ✅ **最终方案：`SizedBox` + `CustomPaint` + 显式 `size`，并在外面
///   套里层 `SizedBox` 把宽高写死。关键是 Row 的 children 里不要给
///   `Expanded`/`Flexible`** —— 上面那些失败案例里，有一半其实是
///   Row 里另有一个 Expanded 的 Text 抢走了宽度。
///
/// 这个类本身是**纯叶子**：给定 size 就占这么大，不多不少，
/// 和 Android 的 `ImageView(wrap_content)` 等义。
class DshIcon extends StatelessWidget {
  final DshGlyph glyph;
  final double size;
  final Color color;

  const DshIcon(this.glyph, {super.key, required this.size, required this.color});

  @override
  Widget build(BuildContext context) {
    final d = _paths[glyph];
    return SizedBox(
      width: size,
      height: size,
      child: CustomPaint(
        size: Size(size, size),
        painter: _PathPainter(d ?? '', color, size),
        isComplex: false,
      ),
    );
  }
}

class _PathPainter extends CustomPainter {
  final String d;
  final Color color;
  final double size;

  _PathPainter(this.d, this.color, this.size);

  static final Map<String, Path> _cache = {};

  /// Material Symbols 的 viewBox 尺寸。
  ///
  /// 原始 SVG 头是 `viewBox="0 -960 960 960"` ——
  /// **宽 960，但 y 的原点是 -960 而不是 0**。
  ///
  /// ⚠️ 这两个常量漏掉任何一个，图标就会「跑到界外」
  /// （阶段②实测：只按 960 缩放、没补 y 平移，图标向上溢出整整 960 单位，
  /// 看起来像「图标浮在文字上方」）。
  static const double _viewBoxSize = 960;
  static const double _viewBoxMinY = 960;

  @override
  void paint(Canvas canvas, Size canvasSize) {
    if (d.isEmpty) return;
    final path = _cache.putIfAbsent(d, () => _parseSvgPath(d));
    final paint = Paint()
      ..color = color
      ..style = PaintingStyle.fill
      ..isAntiAlias = true;

    final w = canvasSize.width;
    final h = canvasSize.height;
    if (w <= 0 || h <= 0) return;

    // 正方形取短边，居中（和 Kotlin 的 box 计算一致）
    final side = w < h ? w : h;
    final k = side / _viewBoxSize;
    final left = (w - side) / 2;
    final top = (h - side) / 2;

    canvas.save();
    canvas.translate(left, top);
    canvas.scale(k, k);
    // viewBox 的 y 从 -960 起：把 -960 映射回 0
    canvas.translate(0, _viewBoxMinY);
    canvas.drawPath(path, paint);
    canvas.restore();
  }

  @override
  bool shouldRepaint(_PathPainter old) =>
      old.d != d || old.color != color || old.size != size;
}




